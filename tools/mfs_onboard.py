    features_text = ", ".join(features) if features else "(add feature names)"
    return "\n".join(
        [
            "# MFS Onboarding Workspace",
            "",
            f"This workspace was generated by MFS at `{mfs_root}`.",
            "",
            "## Included",
            "- `migration_intake.md`",
            "- `candidate_scores.csv`",
            "- `runtime_signals.csv`",
            "- `migration_plan.md`",
            "- `boundaries/*.py`",
            "- `AI_DEV_START.md`",
            "- `context_manifest.json`",
            "- `run_mfs_sequence.ps1`",
            "",
            "## Suggested Flow",
            "1. Read `AI_DEV_START.md` first.",
            "2. Fill `migration_intake.md`.",
            "3. Run `run_mfs_sequence.ps1` (or commands manually).",
            "4. Customize generated boundary stubs and connect to host app.",
            "5. Create cutover manifests and run parity/cutover gates.",
            "",
            f"## Seed Features\n{features_text}",
            "",
            f"Workspace root: `{workspace}`",
        ]
    )


