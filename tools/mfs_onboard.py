#!/usr/bin/env python3
"""Bootstrap an MFS migration workspace inside a legacy repository.

Usage:
  python tools/mfs_onboard.py --target /path/to/legacy-repo --features billing,search --run-discovery
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path
from string import Template
from typing import Dict, List

ROOT = Path(__file__).resolve().parents[1]
TOOLS_DIR = ROOT / "tools"
BOUNDARY_TEMPLATE = ROOT / "templates" / "boundary" / "boundary.py.tmpl"

PROFILE_PRESETS: Dict[str, Dict[str, object]] = {
    "discovery_only": {
        "features": ["feature-a"],
        "run_discovery": True,
        "discovery_top": 10,
        "notes": "Fast initial triage and candidate surfacing.",
    },
    "planning_pack": {
        "features": ["feature-a", "feature-b"],
        "run_discovery": True,
        "discovery_top": 20,
        "notes": "Balanced discovery and planning workspace for AI-led migration design.",
    },
    "cutover_ready": {
        "features": ["feature-a", "feature-b", "feature-c"],
        "run_discovery": True,
        "discovery_top": 25,
        "notes": "Planning + boundary seeds prepared for cutover workflows.",
    },
    "ci_strict": {
        "features": ["feature-a", "feature-b"],
        "run_discovery": True,
        "discovery_top": 30,
        "notes": "High-signal extraction context intended for stricter CI and gate-driven execution.",
    },
}

SOURCE_EXTENSIONS = {
    ".py",
    ".js",
    ".jsx",
    ".ts",
    ".tsx",
    ".go",
    ".java",
    ".kt",
    ".rb",
    ".php",
    ".cs",
    ".rs",
}


def _slugify(raw: str) -> str:
    slug = re.sub(r"[^a-z0-9]+", "-", raw.strip().lower()).strip("-")
    if not slug:
        raise ValueError("Feature name must contain at least one alphanumeric character")
    return slug


def _snake(slug: str) -> str:
    return slug.replace("-", "_")


def _camel(slug: str) -> str:
    return "".join(p.capitalize() for p in slug.split("-"))


def _copy(src: Path, dst: Path, *, force: bool) -> None:
    if dst.exists() and not force:
        return
    dst.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(src, dst)


def _write_text(path: Path, content: str, *, force: bool) -> None:
    if path.exists() and not force:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


def _render_boundary(feature_slug: str, port: int) -> str:
    tpl = Template(BOUNDARY_TEMPLATE.read_text(encoding="utf-8"))
    feature_snake = _snake(feature_slug)
    class_name = f"{_camel(feature_slug)}Boundary"
    return tpl.substitute(
        {
            "feature_slug": feature_slug,
            "class_name": class_name,
            "env_prefix": f"MFS_{feature_snake.upper()}",
            "default_base_url": f"http://localhost:{port}",
            "source_name": f"{feature_snake}_boundary",
            "capabilities_path": f"/v1/{feature_slug}/capabilities",
            "call_path": f"/v1/{feature_slug}",
            "call_method": "POST",
            "factory_name": f"get_{feature_snake}_boundary",
        }
    )


def _plan_skeleton(features: List[str]) -> str:
    lines = [
        "# MFS Migration Plan Skeleton",
        "",
        "## Context",
        "- Legacy app:",
        "- Owner:",
        "- Environment:",
        "",
        "## Candidate Waves",
    ]
    for idx, feat in enumerate(features or ["feature-a", "feature-b"], start=1):
        lines.extend(
            [
                f"### Wave {idx}: {feat}",
                "- Why this feature:",
                "- Contract endpoint:",
                "- Boundary adapter path:",
                "- UI parity risks:",
                "- Rollback trigger:",
                "",
            ]
        )
    lines.extend(
        [
            "## Execution Checklist",
            "- [ ] Run candidate discovery",
            "- [ ] Merge runtime signals",
            "- [ ] Finalize scoring and wave order",
            "- [ ] Scaffold service + boundary",
            "- [ ] Prepare cutover manifest",
            "- [ ] Run UI parity checklist + smoke",
            "- [ ] Promote canary",
            "- [ ] Validate and expand rollout",
            "",
        ]
    )
    return "\n".join(lines)


